
# =========================================================
# MISUKI - BACKEND
# =========================================================

import os

from flask import Flask
from dotenv import load_dotenv


# =========================================================
# ENVIRONMENT
# =========================================================

load_dotenv()


# =========================================================
# APP
# =========================================================

app = Flask(
    __name__
)


# =========================================================
# CONFIG
# =========================================================

app.config["SECRET_KEY"] = os.getenv(
    "SECRET_KEY",
    "misuki-development-key"
)


# =========================================================
# BASIC ROUTE
# =========================================================

@app.route("/")
def index():

    return {
        "name": "Misuki",
        "status": "online"
    }


# =========================================================
# RUN
# =========================================================

if __name__ == "__main__":

    app.run(
        host="0.0.0.0",
        port=int(
            os.getenv(
                "PORT",
                5000
            )
        ),
        debug=False
    )

